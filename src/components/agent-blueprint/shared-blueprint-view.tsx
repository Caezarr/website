"use client";

import Image from "next/image";
import Link from "next/link";
import { useCallback, useEffect, useRef, useState } from "react";
import { useReducedMotion } from "motion/react";
import { HERO_BG_IMAGE } from "@/components/sections/hero";
import { ButtonLink } from "@/components/ui/button";
import { headingClass } from "@/lib/design-tokens";
import type { Locale } from "@/i18n/config";
import { localizeHref } from "@/i18n/routes";
import { blueprintText as t } from "@/lib/agent-blueprint-copy";
import {
  assessmentIdFromUuid,
  weeklyHoursSaved,
  type SharedBlueprint,
} from "@/lib/agent-blueprint-share";
import { trackWebsiteEvent, WEBSITE_EVENTS } from "@/lib/analytics";
import { cn } from "@/lib/utils";
import { BlueprintResults } from "./agent-blueprint-experience";

/** Public, read-only view of a completed blueprint (/ai-agent-blueprint/r/[id]). */
export function SharedBlueprintView({
  blueprint,
  locale,
  meetingUrl,
  wonkaChatUrl,
}: {
  blueprint: SharedBlueprint;
  locale: Locale;
  meetingUrl: string;
  wonkaChatUrl: string;
}) {
  const reducedMotion = useReducedMotion();
  const [selectedAgentIndex, setSelectedAgentIndex] = useState(0);
  const tracked = useRef(false);
  const generateHref = localizeHref("/ai-agent-blueprint", locale);
  const hours = weeklyHoursSaved(blueprint.result);
  const agentCount = blueprint.result.agents.length;

  useEffect(() => {
    if (tracked.current) return;
    tracked.current = true;
    trackWebsiteEvent(WEBSITE_EVENTS.BLUEPRINT_SHARED_VIEW, {
      locale,
      agent_count: agentCount,
    });
  }, [agentCount, locale]);

  const selectAgent = useCallback(
    (index: number, scroll = true) => {
      setSelectedAgentIndex(index);
      if (!scroll) return;
      window.setTimeout(() => {
        document.getElementById("agent-detail-panel")?.scrollIntoView({
          behavior: reducedMotion ? "auto" : "smooth",
          block: "start",
        });
      }, 80);
    },
    [reducedMotion],
  );

  return (
    <>
      <section
        data-theme="dark"
        lang={blueprint.locale}
        className="bg-background text-text relative isolate overflow-hidden"
      >
        <div aria-hidden className="absolute inset-0 -z-10">
          <Image
            src={HERO_BG_IMAGE}
            alt=""
            fill
            priority
            sizes="100vw"
            className="object-cover"
          />
          <div className="from-background/85 via-background/55 to-background/75 absolute inset-0 bg-gradient-to-r" />
        </div>
        <div className="mx-auto grid w-full max-w-[84rem] gap-10 px-6 pt-28 pb-14 md:px-8 md:pt-40 md:pb-20 lg:grid-cols-[1.3fr_0.7fr] lg:items-end lg:px-12">
          <div>
            <span className="type-eyebrow text-blue-300">
              {t(locale, "Shared AI agent blueprint")}
            </span>
            {blueprint.result.sector ? (
              <h1
                className={cn(
                  headingClass.section,
                  "mt-4 max-w-[22ch] text-balance",
                )}
              >
                {blueprint.result.sector}
              </h1>
            ) : (
              <h1 className={cn(headingClass.section, "mt-4")}>
                {t(locale, "AI agent blueprint")}
              </h1>
            )}
            <p className="type-paragraph-m text-text/70 mt-4 max-w-xl">
              {t(
                locale,
                "Generated by Wonka AI from a company’s public website. Company and client names are removed.",
              )}
            </p>
            <div className="mt-7 flex flex-wrap items-center gap-x-6 gap-y-4">
              <ButtonLink
                href={generateHref}
                data-track="blueprint_shared_generate"
                data-blueprint-cta="shared_hero_generate"
              >
                {t(locale, "Generate the blueprint for your company")}
              </ButtonLink>
              <Link
                href={meetingUrl}
                data-track="meeting"
                data-meeting-type="general"
                data-blueprint-cta="shared_hero_call"
                className="type-paragraph-m text-text/80 hover:text-text underline underline-offset-4"
              >
                {t(locale, "Book a 30 min call")}
              </Link>
            </div>
          </div>
          <dl className="grid grid-cols-2 overflow-hidden rounded-sm border border-white/15 bg-black/40 backdrop-blur-md">
            <div className="flex flex-col-reverse p-5">
              <dt className="type-paragraph-s text-text/55">
                {t(locale, "saved / week")}
              </dt>
              <dd className="type-h5 text-blue-300 tabular-nums">
                {hours.min}–{hours.max}h
              </dd>
            </div>
            <div className="flex flex-col-reverse border-l border-white/15 p-5">
              <dt className="type-paragraph-s text-text/55">
                {t(locale, "Recommended agents")}
              </dt>
              <dd className="type-h5 tabular-nums">{agentCount}</dd>
            </div>
          </dl>
        </div>
      </section>

      <BlueprintResults
        response={{
          assessmentId: assessmentIdFromUuid(blueprint.uuid),
          result: { ...blueprint.result, sources: [] },
        }}
        locale={locale}
        meetingUrl={meetingUrl}
        wonkaChatUrl={wonkaChatUrl}
        selectedAgentIndex={selectedAgentIndex}
        onSelectAgent={selectAgent}
        variant="shared"
        importAvailable={blueprint.importAvailable}
      />

      <section
        data-theme="dark"
        className="bg-background text-text relative isolate overflow-hidden"
      >
        <Image
          src="/images/CTA/cta-bg.avif"
          alt=""
          fill
          sizes="100vw"
          className="pointer-events-none -z-10 object-cover opacity-80"
        />
        <div className="mx-auto flex max-w-[84rem] flex-col items-center px-6 py-16 text-center md:px-12 md:py-24">
          <h2 className={cn(headingClass.section, "max-w-[22ch] text-balance")}>
            {t(locale, "Want the same for your company?")}
          </h2>
          <p className="type-body text-text/80 mt-5 max-w-[35rem]">
            {t(locale, "Free, anonymous, ready in about a minute.")}
          </p>
          <ButtonLink
            href={generateHref}
            className="mt-8"
            data-track="blueprint_shared_generate"
            data-blueprint-cta="shared_footer_cta"
          >
            {t(locale, "Generate the blueprint for your company")}
          </ButtonLink>
          <p className="type-paragraph-s text-text/55 mt-5">
            {t(locale, "Prefer to talk first? ")}
            <Link
              href={meetingUrl}
              data-track="meeting"
              data-meeting-type="general"
              data-blueprint-cta="shared_footer_call"
              className="text-text underline underline-offset-4"
            >
              {t(locale, "Book a 30 min call")}
            </Link>
          </p>
        </div>
      </section>
    </>
  );
}
